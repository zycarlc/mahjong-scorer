/**
 * 番種速查表。番數一律取自 FAN，這裏只寫說明及例子。
 * 例子以空格分隔牌組，每組用 parseTiles 的寫法（'123m'、'555z'、'15f'）。
 */
export interface CheatEntry {
  /** 一個或兩個番種（明／暗之分時兩個） */
  names: FanName[];
  desc: string;
  ex?: string;
  /** 每單位計番，例如「每刻」 */
  unit?: string;
  /** 番數不是定值時的寫法 */
  formula?: string;
}

export interface CheatSection {
  title: string;
  entries: CheatEntry[];
}

